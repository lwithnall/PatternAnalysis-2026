def img_sample_grid(entries: list[ADNISliceEntry], grid_shape: tuple[int, int]):
    """
    Save grid of provided ADNI slice entry images
    Leftover grid spaces are left blank

    Args:
        entries : the ADNI slice entries to display
        grid_shape : the shape (rows, cols) of the images to display
    """

    rows, cols = grid_shape

    fig, axs = plt.subplots(
        rows, cols, figsize=(cols * 1.5, rows), layout="constrained"
    )

    for idx, ax in enumerate(axs.flat):
        ax.axis("off")

        # Display next entry if available
        if idx < len(entries):
            entry = entries[idx]
            with Image.open(entry.img_path) as img:
                ax.imshow(img, cmap="gray")

            label = AD_NAME if entry.label == AD_LABEL else NC_NAME
            ax.set_title(f"Patient {entry.patient_id} ({label})")

    save_fig(fig, AUDIT_RESULT_DIR, f"output_{entries[0].label}.png")


def print_split_stats(stats: dict):
    """
    Basic function to print get_split_stats output

    REF: BASED ON CODE GENERATED BY CHAT GPT, CHECK AI DECLARATION
    ENTRY NUMERO UNO (#1)
    """
    print(f"\n===== {stats['split'].upper()} SPLIT =====")
    print(f"Total entries (slices) | {stats['entries']}")
    print(f"Total patients         | {stats['patients']}")

    print("\nPatient distribution")
    print(f"AD | {stats['AD_patients']} patients | {stats['AD_slices']} slices")
    print(f"NC | {stats['NC_patients']} patients | {stats['NC_slices']} slices")

    s = stats["slices_per_patient"]
    print("\nSlices per patient")
    print(f"Min | {s['min']}")
    print(f"Max | {s['max']}")
    print(f"Mean | {s['mean']}")
    print(f"Std | {s['std']}")

    print("\nSlice index range")
    print(f"{stats['slice_index_range'][0]} - {stats['slice_index_range'][1]}")
    print("=" * 30)



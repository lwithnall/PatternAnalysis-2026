
import numpy as np
import matplotlib
matplotlib.use("Agg")

import matplotlib.pyplot as plt

from PIL import Image
from collections import Counter
from dataset import (
    AD_LABEL, NC_LABEL, DATA_DIR, 
    ADNISliceEntry, 
    get_patient_labels,
    generate_datasets
)


def _slice_entry_index(entry: ADNISliceEntry):
    """
    Extract the slice index of ADNI slice entry
    e.g. ~/.../.../396531_78.jpeg -> 78
    """
    return int(entry.img_path.stem.split("_")[1])


def get_split_stats(split: str, entries: list[ADNISliceEntry]):
    """
    Return statistics for entires corresponding to provided split

    Args:
        split   : name of tested data split (e.g. "test", "train")
        entries : the slice entries corresponding with the given split
    """
    patient_counts = Counter(e.patient_id for e in entries)
    patient_labels = get_patient_labels(entries)

    # Number of patients / recordings
    output = {
        "split": split,
        "entries": len(entries),
        "patients": len(patient_counts.keys()),
    }

    # AD vs NC patient counts
    for lbl, lbl_name in ((AD_LABEL, "AD"), (NC_LABEL, "NC")):
        patients = [p for p, l in patient_labels.items() if l == lbl]
        output[f"{lbl_name}_patients"] = len(patients)
        output[f"{lbl_name}_slices"] = sum(patient_counts[p] for p in patients)

    # Distribution of MRI slices amongst patients
    counts = np.array(list(patient_counts.values()))
    output["slices_per_patient"] = {
        "min": int(counts.min()),
        "max": int(counts.max()),
        "mean": round(float(counts.mean()), 2),
        "std": round(float(counts.std()), 2),
    }

    # Range of 'slicde indexes' found throughout data
    idx = [_slice_entry_index(e) for e in entries]
    output["slice_index_range"] = [int(min(idx)), int(max(idx))]
    
    return output


def img_sample_grid(entries: list[ADNISliceEntry], grid_shape: tuple[int, int]):
    """
    Display a grid of provided ADNI slice entry images
    Leftover grid spaces are left blank

    Args:
        entries : the ADNI slice entries to display
        grid_shape : the shape (rows, cols) of the images to display
    """
    
    rows, cols = grid_shape
    
    fig, axs = plt.subplots(
        rows, cols, 
        figsize=(cols * 3, rows), 
        layout='constrained',
        squeeze=False
    )

    for idx, ax in enumerate(axs.flat):
        ax.axis('off')

        # Display next entry if available
        if (idx < len(entries)):
            entry = entries[idx]
            with Image.open(entry.img_path) as img:
                ax.imshow(img, cmap='gray')
            
            label = "AD" if entry.label == AD_LABEL else "NC"
            ax.set_title(f"Patient {entry.patient_id} ({label})")

    plt.savefig(f"output_{entries[0].label}.png", dpi=300, bbox_inces="tight")
    plt.close()


def print_split_stats(stats: dict):
    """
    Basic function to print get_split_stats output
    
    BASED ON CODE GENERATED BY CHAT GPT, CHECK AI DECLARATION 
    ENTRY NUMERO UNO (#1)
    """
    print(f"\n===== {stats['split'].upper()} SPLIT =====")
    print(f"Total entries (slices) | {stats['entries']}")
    print(f"Total patients         | {stats['patients']}")

    print("\nPatient distribution")
    print(f"AD | {stats['AD_patients']} patients | {stats['AD_slices']} slices")
    print(f"NC | {stats['NC_patients']} patients | {stats['NC_slices']} slices")

    s = stats["slices_per_patient"]
    print("\nSlices per patient")
    print(f"Min | {s['min']}")
    print(f"Max | {s['max']}")
    print(f"Mean | {s['mean']}")
    print(f"Std | {s['std']}")

    print("\nSlice index range")
    print(f"{stats['slice_index_range'][0]} - {stats['slice_index_range'][1]}")
    print("=" * 30)


